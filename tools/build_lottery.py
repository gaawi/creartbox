#!/usr/bin/env python3
"""Put the ticket-lottery band on the pages that should carry it.

    python3 tools/build_lottery.py            # write the bands
    python3 tools/build_lottery.py --check    # fail if out of date
    python3 tools/build_lottery.py --off      # take them all out again

The lottery page itself, lottery.html, is an ordinary page and is not
generated. This owns only the band that advertises it elsewhere, so that
on 4 December, when the draw is made, one command removes every trace of
it from the site and leaves nothing to find by hand.

Each band sits between its own markers and is written where a reader is
already thinking about this concert: under the next-concert block on the
home page, beside the ticket buttons on the concert page, at the top of
the visitor guide, and at the top of the calendar.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

OPEN_MARK = "<!-- LOTTERY · generated by tools/build_lottery.py -->"
CLOSE_MARK = "<!-- /LOTTERY -->"
BLOCK = re.compile(re.escape(OPEN_MARK) + r".*?" + re.escape(CLOSE_MARK) + r"\n?", re.S)

# Its own pair, because the popup also lives on index.html and one set of
# markers for two blocks means each pass deletes the other one.
POP_OPEN = "<!-- LOTTERY POPUP · generated by tools/build_lottery.py -->"
POP_CLOSE = "<!-- /LOTTERY POPUP -->"
POP_BLOCK = re.compile(re.escape(POP_OPEN) + r".*?" + re.escape(POP_CLOSE) + r"\n?", re.S)

KICKER = "Free tickets"
TITLE = "Ten pairs of tickets to Winterlight, free."
DEK = ("Write to info@creartbox.nyc with the subject WINTERLIGHT LOTTERY and one "
       "sentence on why you would like to come. Entries close 3 December.")
GO = "Enter &#8594;"

CDN = ("https://creartbox-archive.b-cdn.net/archive-creartbox/"
       "2026-10-30-currents-photos/web")
SHOT = "_DSC0656.jpg"       # the hall, for the story-shaped popup
BAND_SHOT = "_DSC0670.jpg"  # the players, for the band
# the Petroushka stage, cropped clean out of the concert artwork
STAGE = "assets/img/promo/winterlight-stage.jpg"
SHOT_ALT = "CreArtBox playing at The DiMenna Center"

# (path, where the band goes, the anchor it goes after or before)
#   "after"  puts it after the anchor, "before" puts it before.
# The popup goes on the home page only, right after <body>, so it is in
# the document before anything below it is laid out. site.js is what
# opens it; with JavaScript off it is a hidden div and nothing else.
POPUP_PAGE = "index.html"
# index.html opens <body class="hero-transparent">, so match the tag
# rather than a literal string that happens to be true elsewhere
POPUP_ANCHOR = re.compile(r"<body[^>]*>")

PAGES = [
    ("index.html", "after", "<!-- /NEXT EVENT -->", "home"),
    ("concerts/winterlight-2026.html", "before", '        <section class="event-promo">',
     "concert"),
    ("classical-concerts-nyc.html", "after", "<main>", "guide"),
    ("concerts.html", "after", "<main>", "calendar"),
]


def strip(src):
    """Take the band and the popup out, so a generator can compare."""
    return POP_BLOCK.sub("", BLOCK.sub("", src or ""))


def carry(old, new):
    """Put the band from `old` back into a freshly generated page.

    The same contract as tools/seo_block.py. A generator that rewrites a
    page whole has no idea this band exists; without this it would drop
    it on every run and build_lottery would put it back, and the two
    would take turns calling the page stale for ever.
    """
    m = BLOCK.search(old or "")
    if not m or BLOCK.search(new):
        return new
    at = new.find("<main>")
    if at == -1:
        return new
    at += len("<main>")
    return new[:at] + "\n" + m.group(0).rstrip("\n") + new[at:]


def band(prefix, where):
    href = prefix + "lottery.html"
    return (
        '{o}\n'
        '<section class="section" style="padding-top:28px;padding-bottom:28px">\n'
        '  <div class="wrap">\n'
        '    <a class="lotband" href="{href}" data-cb-track="lottery" data-cb-where="{where}">\n'
        '      <span class="lotband-inner">\n'
        '        <span class="lotband-shot">'
        '<img src="{p}{stage}" alt="{alt}" loading="lazy"></span>\n'
        '        <span>\n'
        '          <span class="lotband-k">{kicker}</span>\n'
        '          <span class="lotband-t">{title}</span>\n'
        '          <span class="lotband-d">{dek}</span>\n'
        '        </span>\n'
        '        <span class="lotband-go">{go}</span>\n'
        '      </span>\n'
        '    </a>\n'
        '  </div>\n'
        '</section>\n'
        '{c}\n'
    ).format(o=OPEN_MARK, c=CLOSE_MARK, href=href, where=where,
             kicker=KICKER, title=TITLE, dek=DEK, go=GO,
             p=prefix, stage=STAGE,
             alt="CreArtBox on stage before the Petroushka backdrop")


