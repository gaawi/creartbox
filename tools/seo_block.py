#!/usr/bin/env python3
"""The managed head block that tools/build_seo.py owns.

Every page carries one, holding the canonical link, the social cards
and the JSON-LD graph. The generators that rewrite a whole page import
`strip` and `carry` from here so that the block is neither compared nor
thrown away: `strip` takes it out before a page is compared with what a
generator would write, and `carry` puts the old one back into the new
page. Only build_seo.py writes a fresh one.
"""

import re

OPEN_MARK = "<!-- SEO · generated by tools/build_seo.py -->"
CLOSE_MARK = "<!-- /SEO -->"

BLOCK = re.compile(re.escape(OPEN_MARK) + r".*?" + re.escape(CLOSE_MARK) + r"\n?", re.S)
ICON = re.compile(r'^([ \t]*)<link rel="icon"[^>]*>[ \t]*\n', re.M)


def find(src):
    """The block as it stands in this page, or the empty string."""
    m = BLOCK.search(src or "")
    return m.group(0) if m else ""


def strip(src):
    return BLOCK.sub("", src or "")


def carry(old, new):
    """Put the block from `old` back into the freshly generated `new`."""
    block = find(old)
    if not block or BLOCK.search(new):
        return new
    head_end = new.find("</head>")
    if head_end == -1:
        return new
    head, rest = new[:head_end], new[head_end:]
    if ICON.search(head):
        head = ICON.sub(lambda m: block + m.group(0), head, count=1)
    else:
        head = head.rstrip("\n") + "\n" + block
    return head + rest
