#!/usr/bin/env python3
"""The home page, on the day of a concert.

    python3 tools/build_tonight.py          # write the block
    python3 tools/build_tonight.py --check  # fail if it is out of date

On the day of a production, creartbox.nyc is not a home page. It is the
programme, for the two hundred people walking into the hall with a
phone in their hand and no sheet of paper. So on that day, and only
that day, the site answers with one page: what is on tonight, where
and when, the works in order with their running times, the musicians
playing them, and a way to give afterwards.

It is the first thing on the home page that day, above the hero, and
hidden every other day. The navigation, the footer and the rest of the
page stay exactly where they are: nothing is taken away from anyone
who came looking for something else. A line of script in the head
reads the date in New York - the hall's own clock, not the visitor's -
and sets a class on <html> before anything paints, so the block is
either there from the first frame or not at all. After 7:45 pm in New
York it sets a second class, and the giving block stops asking people
to support the concert and starts asking what they thought of it.

Everything comes from the concert's own page. Change that page, run
this, and the night follows.

    python3 tools/sync_calendar_programs.py && python3 tools/build_tonight.py
"""

import html
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_presenters import PLAYERS                   # noqa: E402

HOME = "index.html"
INDEX = "concerts.html"

HEAD_RE = re.compile(
    r"(<!-- TONIGHT INIT · generated by tools/build_tonight\.py -->\n)"
    r".*?(<!-- /TONIGHT INIT -->)", re.S)
BLOCK_RE = re.compile(
    r"(<!-- TONIGHT · generated by tools/build_tonight\.py -->\n)"
    r".*?(<!-- /TONIGHT -->)", re.S)

ROW_RE = re.compile(r'<tr[^>]*data-new-production[^>]*>.*?</tr>', re.S)
HREF_RE = re.compile(r'class="title-cell"><a href="([^"]+)"')
MONTHS = ("january february march april may june july august september "
          "october november december").split()
PORTRAIT = {slug: photo for _, _, slug, photo in PLAYERS}


def clean(fragment):
    # entities out here, so that what goes back in is escaped once
    txt = re.sub(r"<[^>]+>", " ", fragment or "")
    return re.sub(r"\s+", " ", html.unescape(txt).replace("\u00a0", " ")).strip()


def concert_page():
    row = ROW_RE.search(open(INDEX, encoding="utf-8").read())
    if not row:
        sys.exit("no new production in the calendar")
    href = HREF_RE.search(row.group(0))
    if not href:
        sys.exit("the featured calendar row has no link to a concert page")
    return href.group(1)


def read(path):
    src = open(path, encoding="utf-8").read()
    when = clean(re.search(r'<div class="concert-when-where">(.*?)</div>',
                           src, re.S).group(1))
    parts = [p.strip() for p in html.unescape(when).split("·")]
    date = parts[0]
    m = re.match(r"([A-Za-z]+)\s+(\d{1,2}),\s*(\d{4})", date)
    if not m or m.group(1).lower() not in MONTHS:
        sys.exit("cannot read the date of " + path)
    iso = "%s-%02d-%02d" % (m.group(3), MONTHS.index(m.group(1).lower()) + 1,
                            int(m.group(2)))

    works = []
    block = re.search(r'<ul class="pgm-list">(.*?)</ul>', src, re.S)
    for li in re.findall(r"<li>(.*?)</li>", block.group(1), re.S) if block else []:
        comp = re.search(r'<span class="pgm-composer">(.*?)</span>', li, re.S)
        work = re.search(r'<span class="pgm-work">(.*?)</span>', li, re.S)
        if not (comp and work):
            continue
        raw_c = comp.group(1).split('<span class="pgm-tag">')
        tag = clean(raw_c[1]) if len(raw_c) > 1 else ""
        raw_w = work.group(1).split('<span class="pgm-mins">')
        mins = re.search(r"(\d+)", raw_w[1]) if len(raw_w) > 1 else None
        title = clean(raw_w[0])
        scoring = ""
        paren = re.search(r"\s*\(([^()]*)\)\s*$", title)
        if paren:
            title, scoring = title[:paren.start()].strip(), paren.group(1)
        works.append({"composer": clean(raw_c[0]), "tag": tag, "title": title,
                      "scoring": scoring, "mins": mins.group(1) if mins else ""})

    people = []
    block = re.search(r'<ul class="art-list">(.*?)</ul>', src, re.S)
    for li in re.findall(r"<li>(.*?)</li>", block.group(1), re.S) if block else []:
        name = re.search(r'<span class="art-name">(.*?)</span>', li, re.S)
        role = re.search(r'<span class="art-role">(.*?)</span>', li, re.S)
        href = re.search(r'href="\.\./(artists/([a-z-]+)\.html)"', li)
        if not name:
            continue
        slug = href.group(2) if href else ""
        people.append({"name": clean(name.group(1)),
                       "role": clean(role.group(1)) if role else "",
                       "href": href.group(1) if href else "",
                       "photo": PORTRAIT.get(slug, "")})

    run = re.search(r"Approximately (\d+) minutes[^<.]*", src)
    booklet = "programs/%s.html" % os.path.splitext(os.path.basename(path))[0]
    pdf = "downloads/%s-program.pdf" % os.path.splitext(os.path.basename(path))[0]
    return {
        "path": path,
        "title": clean(re.search(r'<h1 class="event-title">(.*?)</h1>', src, re.S).group(1)),
        "series": clean(re.search(r'<div class="event-series">(.*?)</div>', src, re.S).group(1)),
        "iso": iso,
        "date": date,
        "time": parts[1] if len(parts) > 1 else "",
        "venue": parts[2] if len(parts) > 2 else "",
        "address": " · ".join(parts[3:]) if len(parts) > 3 else "",
        "works": works,
        "people": people,
        "run": clean(run.group(0)) if run else "",
        "booklet": booklet if os.path.exists(booklet) else "",
        "pdf": pdf if os.path.exists(pdf) else "",
    }


def weekday(iso):
    import datetime
    return datetime.date(*map(int, iso.split("-"))).strftime("%A")


def head_block(ev):
    return (
        '<script id="cb-tonight">(function(){try{'
        'if(location.search.indexOf("full")>-1)return;'
        'var p=new Intl.DateTimeFormat("en-CA",{timeZone:"America/New_York",'
        'year:"numeric",month:"2-digit",day:"2-digit",hour:"2-digit",minute:"2-digit",'
        'hour12:false}).formatToParts(new Date()),g={};'
        'p.forEach(function(x){g[x.type]=x.value;});'
        'if(g.year+"-"+g.month+"-"+g.day!=="%s")return;'
        'var r=document.documentElement;r.classList.add("concert-day");'
        'if(Number(g.hour)*60+Number(g.minute)>=%d)r.classList.add("after-curtain");'
        '}catch(e){}})();</script>\n' % (ev["iso"], 19 * 60 + 45))


def works_html(ev):
    rows = []
    for w in ev["works"]:
        tag = ('<span class="tn-tag">%s</span>' % html.escape(w["tag"])) if w["tag"] else ""
        scoring = ('\n        <p class="tn-scoring">%s</p>' % html.escape(w["scoring"])) if w["scoring"] else ""
        mins = ('<span class="tn-min">%s&#x2032;</span>' % w["mins"]) if w["mins"] else ""
        rows.append(
            '      <li class="tn-work">\n'
            '        <p class="tn-composer">{c}{tag}</p>\n'
            '        <p class="tn-name">{t}{m}</p>{s}\n'
            '      </li>'.format(c=html.escape(w["composer"]), tag=tag,
                                 t=html.escape(w["title"]), m=mins, s=scoring))
    return "\n".join(rows)


def people_html(ev):
    rows = []
    for p in ev["people"]:
        shot = ('<span class="tn-face"><img src="%s" alt="%s" loading="lazy" '
                'width="56" height="56"></span>' % (p["photo"], html.escape(p["name"]))
                ) if p["photo"] else '<span class="tn-face tn-face-none"></span>'
        inner = ('{shot}<span class="tn-who"><span class="tn-person">{n}</span>'
                 '<span class="tn-role">{r}</span></span>'
                 '<span class="tn-go" aria-hidden="true">&#8594;</span>'
                 .format(shot=shot, n=html.escape(p["name"]), r=html.escape(p["role"])))
        rows.append('      <li>%s</li>' % (
            '<a href="%s">%s</a>' % (p["href"], inner) if p["href"] else
            '<span class="tn-plain">%s</span>' % inner))
    return "\n".join(rows)


def block(ev):
    links = []
    if ev["booklet"]:
        links.append('      <a href="%s">Programme notes <span class="tn-ar">&#8594;</span></a>'
                     % ev["booklet"])
    if ev["pdf"]:
        links.append('      <a href="%s" download>Programme &#183; PDF <span class="tn-ar">&#8595;</span></a>'
                     % ev["pdf"])
    links.append('      <a href="%s">About this concert <span class="tn-ar">&#8594;</span></a>'
                 % ev["path"])
    links.append('      <a href="concerts.html">What we play next <span class="tn-ar">&#8594;</span></a>')
    links.append('      <a href="support.html">Other ways to support us <span class="tn-ar">&#8594;</span></a>')

    where = "<br>".join(x for x in (html.escape(ev["venue"]), html.escape(ev["address"])) if x)
    return """<section class="tonight" aria-label="Tonight at CreArtBox">
  <div class="tn-wrap">

    <p class="tn-note">
      <span class="tn-badge">Tonight</span>
      <span class="tn-note-t">This page is set up for tonight&#x27;s concert.
        <a href="#site">The whole site is below <span class="tn-ar">&#8595;</span></a></span>
    </p>

    <header class="tn-head">
      <p class="tn-series">{series}</p>
      <h1 class="tn-title">{title}</h1>
      <p class="tn-when"><strong>{weekday}, {date}</strong> \u00b7 {time}<br>{where}</p>
    </header>

    <section class="tn-card">
      <h2 class="tn-h">The programme</h2>
      <ol class="tn-works">
{works}
      </ol>
      <p class="tn-run">{run}</p>
    </section>

    <aside class="tn-give">
      <p class="tn-give-h tn-before">Support what you hear tonight</p>
      <p class="tn-give-h tn-after">If you enjoyed tonight</p>
      <p class="tn-give-t">CreArtBox is a 501(c)(3) non-profit. Tickets cover a part of
        an evening like this one; what they do not cover is what pays the musicians and
        commissions the next score.</p>
      <a class="tn-give-btn" href="support.html" data-donate data-cb-track="donate" data-cb-where="tonight">
        Donate <span class="tn-ar">&#8594;</span></a>
      <p class="tn-give-n">Secure payment &#183; Tax-deductible in the United States</p>
    </aside>

    <section class="tn-card">
      <h2 class="tn-h">On stage tonight</h2>
      <ul class="tn-people">
{people}
      </ul>
    </section>

    <nav class="tn-more">
{links}
    </nav>

    <p class="tn-end"><a href="#site">The rest of creartbox.nyc
      <span class="tn-ar">&#8595;</span></a></p>

  </div>
</section>
""".format(series=html.escape(ev["series"]), title=html.escape(ev["title"]),
           weekday=weekday(ev["iso"]), date=html.escape(ev["date"]),
           time=html.escape(ev["time"]), where=where, works=works_html(ev),
           run=html.escape(ev["run"]), people=people_html(ev),
           links="\n".join(links))


def main():
    check = "--check" in sys.argv
    ev = read(concert_page())
    src = open(HOME, encoding="utf-8").read()
    if not (HEAD_RE.search(src) and BLOCK_RE.search(src)):
        sys.exit(
            "no generated blocks in {}. Add\n"
            "  <!-- TONIGHT INIT · generated by tools/build_tonight.py -->\n"
            "  <!-- /TONIGHT INIT -->\n"
            "inside <head>, and\n"
            "  <!-- TONIGHT · generated by tools/build_tonight.py -->\n"
            "  <!-- /TONIGHT -->\n"
            "as the first thing inside <main>.".format(HOME))

    out = HEAD_RE.sub(lambda m: m.group(1) + head_block(ev) + m.group(2), src, count=1)
    out = BLOCK_RE.sub(lambda m: m.group(1) + block(ev) + m.group(2), out, count=1)

    if check:
        if out != src:
            print("the concert-day home page is out of date (%s, %s)"
                  % (ev["title"], ev["iso"]))
            print("\nRun: python3 tools/build_tonight.py")
            return 1
        print("concert-day home page ready: %s, %s, %d work(s), %d musician(s)"
              % (ev["title"], ev["iso"], len(ev["works"]), len(ev["people"])))
        return 0

    if out != src:
        open(HOME, "w", encoding="utf-8").write(out)
        print("tonight: %s · %s · %d work(s), %d musician(s)"
              % (ev["title"], ev["iso"], len(ev["works"]), len(ev["people"])))
    else:
        print("already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
