#!/usr/bin/env python3
"""Give the home page the concert that has just happened.

    python3 tools/sync_last_event.py            # rewrite the block
    python3 tools/sync_last_event.py --check    # fail if out of date

Under the next production, the last one: four photographs from the
night, what it was, and the way into its page in the archive. A
visitor who arrives the week after a concert should find that it
happened, rather than a calendar that has quietly dropped it.

A production earns this block when it has photographs, which is the
same thing as having a page built by tools/build_photo_page.py. The
most recent of those is the one shown, so filing the next concert and
its photographs is all it takes to move this on.

Everything comes from that page and from data/archive-photos.txt.
"""

import html
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_photo_page import CDN, PAGES, photos                # noqa: E402

HOME = "index.html"
MONTHS = ("Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec").split()
FULL = ("January February March April May June July August September "
        "October November December").split()

BLOCK_RE = re.compile(
    r"(<!-- LAST EVENT · generated by tools/sync_last_event\.py -->\n)"
    r".*?(<!-- /LAST EVENT -->)", re.S)


def newest():
    """The most recently photographed production."""
    def key(spec):
        return (int(spec["year"]), MONTHS.index(spec["month"]) + 1, int(spec["day"]))
    return max(PAGES, key=key) if PAGES else None


def opening_paragraph(path):
    if not os.path.exists(path):
        return ""
    src = open(path, encoding="utf-8").read()
    block = re.search(r'<section class="event-description">(.*?)</section>', src, re.S)
    if not block:
        return ""
    for p in re.findall(r"<p[^>]*>(.*?)</p>", block.group(1), re.S):
        text = re.sub(r"\s+", " ", p).strip()
        if len(re.sub(r"<[^>]+>", "", text)) > 60:
            return text
    return ""


def render(spec, shots):
    page = "archive/%s.html" % spec["slug"]
    base = "%s/%s/web" % (CDN, spec["folder"])
    chosen = [n for n in spec.get("top", []) if n in shots.get("web", [])] \
        or shots.get("web", [])[:4]
    title = html.escape(spec["title"])

    strip = "".join(
        '<img src="{b}/{n}" alt="{t}, {m} {y}" loading="lazy">'.format(
            b=base, n=html.escape(n), t=title, m=FULL[MONTHS.index(spec["month"])],
            y=spec["year"])
        for n in chosen)

    series = spec["part_of"]
    head, sep, tail = series.rpartition(" · ")
    caption = (head + sep + "<em>" + tail + "</em>") if sep else "<em>" + series + "</em>"

    buttons = ['<a href="{p}" class="btn btn-stamp btn-l">Photographs from the night '
               '<span class="ar">&#8594;</span></a>'.format(p=page)]
    if spec.get("booklet") and os.path.exists(spec["booklet"]):
        buttons.append('<a href="{b}" class="btn btn-l">Read the programme</a>'
                       .format(b=spec["booklet"]))
    buttons.append('<a href="archive.html" class="btn btn-l">The whole archive</a>')

    return """<section class="section lastev">
  <div class="wrap">
    <div class="section-title">
      <hr class="rule">
      <div class="head"><span class="label">Last concert</span><span class="bar"></span><span class="label ital">{caption}.</span></div>
      <hr class="rule">
      <h2 class="h-feature">{month} {year}</h2>
    </div>

    <a class="lastev-strip" href="{page}" aria-label="Photographs from {title}, {month} {year}">
      {strip}
    </a>

    <div class="lastev-body">
      <h3 class="h-title lastev-title">{title}</h3>
      <p class="body-l lastev-text">{blurb}</p>
      <div class="lastev-actions">
        {buttons}
      </div>
    </div>
  </div>
</section>
""".format(caption=caption, month=FULL[MONTHS.index(spec["month"])], year=spec["year"],
           page=page, title=title, strip=strip,
           blurb=opening_paragraph(page), buttons="\n        ".join(buttons))


def main():
    check = "--check" in sys.argv
    spec = newest()
    if not spec:
        print("no photographed production to show")
        return 0
    shots = photos().get(spec["slug"], {})
    if not shots.get("web"):
        print("no photographs listed for " + spec["slug"])
        return 0

    src = open(HOME, encoding="utf-8").read()
    if not BLOCK_RE.search(src):
        sys.exit(
            "no generated block in {}. Add\n"
            "  <!-- LAST EVENT · generated by tools/sync_last_event.py -->\n"
            "  <!-- /LAST EVENT -->\n"
            "under the next-event block.".format(HOME))

    out = BLOCK_RE.sub(lambda m: m.group(1) + render(spec, shots) + m.group(2), src, count=1)

    if check:
        if out != src:
            print('home page is not showing "%s" as the last concert' % spec["title"])
            print("\nRun: python3 tools/sync_last_event.py")
            return 1
        print("home page looks back at: %s · %s %s"
              % (spec["title"], spec["month"], spec["year"]))
        return 0

    if out != src:
        open(HOME, "w", encoding="utf-8").write(out)
        print("last concert: %s · %s %s · %d photograph(s) listed"
              % (spec["title"], spec["month"], spec["year"], len(shots["web"])))
    else:
        print("already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
